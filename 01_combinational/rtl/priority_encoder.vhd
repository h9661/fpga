--=============================================================================
-- priority_encoder.vhd — 8-입력 우선순위 인코더 (8-to-3)
--=============================================================================
-- 【이 파일에서 배우는 것】
--   1. "우선순위 인코더" 의 용도와 동작
--   2. VHDL 에서 for 루프가 합성될 때 무슨 일이 벌어지는가 (루프 언롤링)
--   3. exit 문을 하드웨어로 해석하는 방법
--   4. variable 을 이용한 "초기값 + 조건부 갱신" 패턴
--
-- ─────────────────────────────────────────────────────────────────────────
-- 【우선순위 인코더란?】
--   여러 비트 중 '1' 이 하나라도 있을 때, 가장 "우선순위가 높은" 비트의 인덱스
--   를 내보내는 회로. 여기선 "가장 높은 번호의 비트" 가 우선.
--
--   예:
--     d = "00000001" → y = "000" (비트 0), valid = '1'
--     d = "00010100" → y = "100" (비트 4, 비트 2 도 1 이지만 4 가 우선), valid = '1'
--     d = "00000000" → y = "000", valid = '0' (아무것도 없음)
--
-- 【용도】
--   * 인터럽트 컨트롤러: 여러 인터럽트 중 가장 우선순위 높은 것을 선택
--   * 부동소수점 연산의 선행 0 개수 세기 (leading-zero count)
--   * FIFO/큐 의 "가장 오래된 항목" 선택
--
-- 【하드웨어 구현 감각】
--   게이트 레벨로는 OR 게이트 체인 + AND 게이트 조합.
--   FPGA 에선 LUT 몇 개로 구현됨.
--=============================================================================

library ieee;
    use ieee.std_logic_1164.all;
    use ieee.numeric_std.all;    -- to_unsigned 변환용

entity priority_encoder is
    port (
        d     : in  std_logic_vector(7 downto 0);  -- 8개 입력 비트
        y     : out std_logic_vector(2 downto 0);  -- 가장 높은 '1' 의 인덱스 (0..7)
        valid : out std_logic                      -- 하나라도 '1' 이 있으면 '1'
    );
end entity;

architecture rtl of priority_encoder is
begin
    --------------------------------------------------------------------------
    -- 조합 프로세스: sensitivity list 에 d 만 (다른 입력 없음).
    --------------------------------------------------------------------------
    process(d)
        -- 지역 variable 두 개. 왜 signal 이 아닌 variable 인가?
        --   signal 은 "<=" 대입 후 프로세스 끝에서야 실제 반영 (delta 지연).
        --   루프 안에서 "찾으면 바로 저장 후 탈출" 을 하려면 즉시 반영이 필요.
        --   variable ":=" 는 즉시 반영되므로 이 패턴에 딱 맞다.
        variable y_v     : std_logic_vector(2 downto 0);
        variable valid_v : std_logic;
    begin
        -- 【기본값 + 조건부 덮어쓰기 패턴】
        --   먼저 "못 찾은 경우" 기본값을 깔고, 찾으면 덮어쓴다.
        --   이렇게 해야 모든 실행 경로에서 y_v/valid_v 가 반드시 한 번은 대입되어
        --   latch 생성이 방지된다.
        y_v     := (others => '0');
        valid_v := '0';

        -- 【for 루프가 하드웨어에서는 무슨 뜻인가?】
        --   소프트웨어에서 for 루프는 시간축상의 반복 → 한 번에 한 이터레이션씩.
        --   하드웨어에선 루프 횟수가 컴파일 시점에 알려져 있으므로 합성기가 루프를
        --   "펼쳐" 버린다 (루프 언롤링). 결과적으로 아래 8번 반복은
        --
        --      d(7) 체크 → d(6) 체크 → ... → d(0) 체크
        --
        --   의 조합 논리 8단계로 "동시에" 평가되는 회로로 매핑된다. 그래서
        --   시뮬상 "7부터 내려가며 순차 탐색" 처럼 보이지만 실제 회로는 1 사이클
        --   (전파지연) 만에 결과를 낸다.
        --
        -- 문법:
        --   for <loop_var> in <범위> loop ... end loop;
        --   <loop_var> 는 루프 지역 상수 (루프 내부에서 대입 불가).
        --   7 downto 0 → 7,6,5,...,0 순서로 순회.
        for i in 7 downto 0 loop
            if d(i) = '1' then
                -- to_unsigned(i, 3): 정수 i 를 3비트 unsigned 벡터로 변환 →
                --                    std_logic_vector 로 재해석.
                y_v     := std_logic_vector(to_unsigned(i, 3));
                valid_v := '1';
                -- 【exit 문】
                --   C 의 break 와 동일. 가장 안쪽 loop 를 즉시 탈출.
                --   "exit <label>" 로 바깥 loop 를 탈출하는 것도 가능.
                --
                --   하드웨어적으로 exit 는 "이후 반복에서 결과를 덮어쓰지 않게 하라"
                --   는 뜻으로 해석되어, 언롤된 체인의 우선순위 방향이 결정된다.
                --   (여기선 "가장 먼저 만난 i 가 결과" → i=7 부터 검사했으므로
                --    가장 높은 인덱스가 우선.)
                exit;
            end if;
        end loop;

        -- 루프 끝난 뒤 한 번만 signal 에 반영. variable 은 process 밖에서 볼
        -- 수 없으므로 외부 포트엔 반드시 signal 로 옮겨야 한다.
        y     <= y_v;
        valid <= valid_v;
    end process;
end architecture;
